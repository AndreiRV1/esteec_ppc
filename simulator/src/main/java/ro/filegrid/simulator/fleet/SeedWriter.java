package ro.filegrid.simulator.fleet;

import java.io.BufferedWriter;
import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;

/** Writes the fleet as idempotent SQL inserts into {@code filegrid.meter}. */
public final class SeedWriter {

    private static final int ROWS_PER_INSERT = 1_000;

    private SeedWriter() {}

    public static void write(Fleet fleet, Path file) throws IOException {
        Path parent = file.toAbsolutePath().getParent();
        if (parent != null) Files.createDirectories(parent);
        try (BufferedWriter out = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) {
            write(fleet, out);
        }
    }

    public static void write(Fleet fleet, Writer out) throws IOException {
        out.write("-- Generated by the FileGrid meter simulator. Do not edit: run `make seed`.\n");
        out.write("-- seed=%d meters=%d fingerprint=%s\n".formatted(fleet.seed(), fleet.size(), fleet.fingerprint()));
        out.write("BEGIN;\n");
        List<Meter> meters = fleet.meters();
        for (int from = 0; from < meters.size(); from += ROWS_PER_INSERT) {
            out.write("INSERT INTO filegrid.meter (id, region, county, locality, latitude, longitude) VALUES\n");
            int to = Math.min(from + ROWS_PER_INSERT, meters.size());
            for (int i = from; i < to; i++) {
                Meter m = meters.get(i);
                out.write(String.format(Locale.ROOT, "  (%s, %s, %s, %s, %.6f, %.6f)%s\n",
                        literal(m.id()), literal(m.region().name()), literal(m.locality().county()),
                        literal(m.locality().name()), m.latitude(), m.longitude(), i + 1 < to ? "," : ""));
            }
            out.write("ON CONFLICT (id) DO NOTHING;\n");
        }
        out.write("COMMIT;\n");
    }

    private static String literal(String s) {
        return "'" + s.replace("'", "''") + "'";
    }
}
